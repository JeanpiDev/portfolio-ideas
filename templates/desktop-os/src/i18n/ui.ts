export const ui = { en, es } as const;
export type UIKey = keyof typeof en;

/** `{name}` and `{first}` in any string are filled from profile.ts. */
const fill = (s: string) => s.replaceAll('{name}', profile.name).replaceAll('{first}', profile.firstName);

export function useTranslations(lang: Lang) {
  return (key: UIKey, vars?: Record<string, string | number>) => {
    let s = fill(ui[lang][key] ?? ui.en[key]);
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

/** Subset of strings the client-side scripts need (serialized into the page as JSON). */
export function clientStrings(lang: Lang) {
  const keys = Object.keys(en).filter((k) =>
    /^(ai\.|err\.|buddy\.|win\.|theme\.|start\.|explorer\.items|explorer\.item|explorer\.views|contact\.copied)/.test(k),
  ) as UIKey[];
  return Object.fromEntries(keys.map((k) => [k, fill(ui[lang][k])]));
}
